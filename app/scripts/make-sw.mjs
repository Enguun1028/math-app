// After the build: write dist/sw.js, the service worker (2026-10-21: "smooth on poor phones").
// It keeps the app on the phone, so a return visit opens from the phone itself and the app also opens offline.
//   Page (/): network first, so a new version shows at once; the saved copy is used offline or when the
//     network has not answered within 3 s.
//   /assets/*: saved on install (every file of this build) and served from the phone; names change per version.
//   /extras/*, /vendor/*: served from the phone and refreshed in the background.
//   Anything else (PostHog under /rx, other sites): untouched.
// The cache name carries a hash of this build's file list, so an old version's files are removed when the new
// service worker takes over (after every old tab is closed, so an open page never loses its files).
import { readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const assets = readdirSync(new URL('../dist/assets/', import.meta.url)).sort().map((f) => '/assets/' + f);
const version = createHash('sha1').update(assets.join('\n')).digest('hex').slice(0, 10);

const sw = `// Generated by scripts/make-sw.mjs; see there.
const CACHE = 'mm-${version}';
const SHELL = ['/', ...${JSON.stringify(assets)}];

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('mm-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});

const fresh = (req) => fetch(req).then((res) => {
  if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
  return res;
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin || url.pathname.startsWith('/rx/')) return;

  if (req.mode === 'navigate') {
    // Network first; the saved page if the network fails or is slower than 3 s.
    e.respondWith(new Promise((resolve) => {
      let done = false;
      const fallback = () => caches.match('/').then((r) => { if (!done && r) { done = true; resolve(r); } });
      const timer = setTimeout(fallback, 3000);
      fetch(req).then((res) => {
        clearTimeout(timer);
        if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put('/', copy)); }
        if (!done) { done = true; resolve(res); }
      }, () => { clearTimeout(timer); fallback().then(() => { if (!done) { done = true; resolve(Response.error()); } }); });
    }));
    return;
  }
  if (url.pathname.startsWith('/assets/')) {
    e.respondWith(caches.match(req).then((hit) => hit || fresh(req)));
    return;
  }
  if (url.pathname.startsWith('/extras/') || url.pathname.startsWith('/vendor/')) {
    e.respondWith(caches.match(req).then((hit) => {
      const net = fresh(req).catch(() => hit);
      return hit || net;
    }));
  }
});
`;
writeFileSync(new URL('../dist/sw.js', import.meta.url), sw);
console.log(`make-sw: ${assets.length} files, cache mm-${version}`);
