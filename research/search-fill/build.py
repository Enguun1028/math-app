"""Copy the search-fill research (research/search-fill/*.json) into the app.
Run: python research/search-fill/build.py   (after any change here)

Writes:
  app/content/ideas-named.json  named formulas, theorems and rules (Виетийн теорем, Хероны томьёо…):
                                each one gets its own search answer page (#/c/<id>) and grows out of a map topic.
  app/content/topic-why.json    per map topic: why it is true (proof or derivation) and where it comes from (history).

Checks: valid JSON, no id clashes with map topics, every "from" id exists, no slash fractions in shown text.
Everything here is DRAFT until the owner or a teacher checks it."""
import glob, json, os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))
app = os.path.join(root, 'app')
topics = {c['id'] for c in json.load(open(os.path.join(app, 'content', 'map.json'), encoding='utf8'))['concepts']}
concepts = json.load(open(os.path.join(app, 'content', 'concepts.json'), encoding='utf8'))

problems = []
# Digits on both sides of a slash read as a fraction; the app must show them stacked (\frac{a}{b}).
SLASH = re.compile(r'(?<![\w/])\d+/\d+(?![\w/])')


def shown_text(v):
    if isinstance(v, str):
        return [v]
    if isinstance(v, list):
        return [t for x in v for t in shown_text(x)]
    if isinstance(v, dict):
        return [t for k, x in v.items() if k not in ('src', 'formulas', 'aliases') for t in shown_text(x)]
    return []


named = {'_note': 'Generated by research/search-fill/build.py from research/search-fill/named-*.json. Draft until the owner checks it.'}
for path in sorted(glob.glob(os.path.join(here, 'named-*.json'))):
    for k, v in json.load(open(path, encoding='utf8')).items():
        if k.startswith('_'):
            continue
        if k in topics or k in concepts or k in named:
            problems.append(f'{os.path.basename(path)}: id {k} already used')
        for f in v.get('from', []):
            if f not in topics:
                problems.append(f'{k}: unknown from {f}')
        for t in shown_text(v):
            if SLASH.search(t):
                problems.append(f'{k}: slash fraction in "{t[:60]}"')
        named[k] = v

why = {'_note': 'Generated by research/search-fill/build.py from research/search-fill/why-*.json. Draft until the owner checks it.'}
for path in sorted(glob.glob(os.path.join(here, 'why-*.json'))):
    for k, v in json.load(open(path, encoding='utf8')).items():
        if k.startswith('_'):
            continue
        if k not in topics:
            problems.append(f'{os.path.basename(path)}: unknown topic {k}')
        for t in shown_text(v):
            if SLASH.search(t):
                problems.append(f'{k}: slash fraction in "{t[:60]}"')
        why[k] = {**why.get(k, {}), **v}  # later files add fields (e.g. why-history-*.json adds history)

for p in problems:
    print('PROBLEM', p)
with open(os.path.join(app, 'content', 'ideas-named.json'), 'w', encoding='utf8') as f:
    json.dump(named, f, ensure_ascii=False)
with open(os.path.join(app, 'content', 'topic-why.json'), 'w', encoding='utf8') as f:
    json.dump(why, f, ensure_ascii=False)
print(f'named ideas: {len(named) - 1}, topics with why/history: {len(why) - 1}, problems: {len(problems)}')
sys.exit(1 if problems else 0)
