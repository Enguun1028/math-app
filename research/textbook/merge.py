"""Merge research/textbook/content-g*.json into app/content/topic-content.json.
Run: python research/textbook/merge.py   (after any content file changes)
Checks: valid ids, required fields, no form-feed or slash-fraction mistakes."""
import json, os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))
ids = {c['id'] for c in json.load(open(os.path.join(root, 'app', 'content', 'map.json'), encoding='utf8'))['concepts']}
merged, problems, per = {}, [], {}
for f in sorted(os.listdir(here)):
    if not re.fullmatch(r'content-g\d+b?\.json', f):
        continue
    d = json.load(open(os.path.join(here, f), encoding='utf8'))
    for k, v in d.items():
        if k.startswith('_'):
            continue
        if k not in ids:
            problems.append(f'{f}: unknown topic id {k}')
            continue
        if k in merged:
            problems.append(f'{f}: {k} already in another file, kept the first')
            continue
        if not v.get('def'):
            problems.append(f'{f}: {k} has no definition')
        txt = json.dumps(v, ensure_ascii=False)
        if '\\f' in txt.replace('\\\\frac', '') or '\x0c' in txt:
            problems.append(f'{f}: {k} has a broken \\frac')
        merged[k] = v
        per[f] = per.get(f, 0) + 1
out = {'_note': 'Generated by research/textbook/merge.py from content-g*.json (written from the official 2020 textbooks on econtent.edu.mn, own wording and numbers). Draft until the owner checks it.', **merged}
json.dump(out, open(os.path.join(root, 'app', 'content', 'topic-content.json'), 'w', encoding='utf8'), ensure_ascii=False, indent=1)
print(per, '| total', len(merged), 'topics')
for p in problems:
    print('PROBLEM', p)
