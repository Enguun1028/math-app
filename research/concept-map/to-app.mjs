// Turns the concept map draft into the app's content file: app/content/map.json.
// Run: node research/concept-map/to-app.mjs (after every change to draft-v1.js)
//
// The app keeps a few things from the old 39-topic map (formula badges, short texts) by carrying them
// over to the matching new concept. OLD_TOPICS is that match, and the app also uses it to move a
// student's saved "Мэднэ" marks from old topic ids to the new ones.
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { CONCEPTS, EDGES, BRANCHES, STRANDS } from './draft-v1.js';

const require = createRequire(import.meta.url);
const oldTopics = require('../../app/content/topics-v1.json');

// old topic id -> new concept id
export const OLD_TOPICS = {
  n1: 'b-place', n2: 'b-add', n3: 'b-mul', n9: 'int', n4: 'gcd', n5: 'frac', n8: 'ratio', n6: 'dec', n7: 'pct',
  g1: 'angle', g2: 'tri', g3: 'perim-area', d1: 'average', a1: 'expr', f1: 'coord', a2: 'lin-eq', a3: 'ineq',
  a4: 'pow', g5: 'pyth', g4: 'vol-surf', d2: 'prob', d3: 'perm-comb', f2: 'linear', a6: 'system', a5: 'factor',
  g7: 'circle', a7: 'quad-eq', f3: 'quad-fn', g6: 'similar', f5: 'trig-right', d4: 'spread', f4: 'exp-fn',
  f6: 'trig-fn', f7: 'fn-props', c1: 'seq', c2: 'deriv', c3: 'deriv-app', c4: 'integral', c5: 'def-int',
};

// Same colours as the review page the owner approved (2026-10-13).
const STRAND_COLOR = { num: '#5cc8ff', alg: '#a78bfa', geo: '#4fe3b0', meas: '#ffd166', stat: '#ff7aa8', calc: '#ff9f5c' };
const GRADE_COLOR = ['#5cc8ff', '#4fe3b0', '#a78bfa', '#ffd166', '#ff7aa8', '#ff9f5c', '#7aa2ff', '#4fd1e3'];

const carried = {};
for (const t of oldTopics) carried[OLD_TOPICS[t.id]] = t;

const map = {
  _note: 'Generated by research/concept-map/to-app.mjs from draft-v1.js. Do not edit by hand. Names, links and reasons are Claude drafts until the owner checks them.',
  strands: Object.fromEntries(STRANDS.map(([id, name]) => [id, { name, color: STRAND_COLOR[id] }])),
  branches: BRANCHES.map(([id, name]) => ({ id, name })),
  gradeColors: GRADE_COLOR,
  oldTopics: OLD_TOPICS,
  concepts: CONCEPTS.map(([id, name, en, branches, strand, grade, codes, mode]) => ({
    id, name, en, branches, strand, grade, codes, mode,
    ...(carried[id] ? { formula: carried[id].formula, text: carried[id].text } : {}),
  })),
  edges: EDGES.map(([from, to, type, why]) => ({ from, to, type, why })),
};

writeFileSync(new URL('../../app/content/map.json', import.meta.url), JSON.stringify(map, null, 1) + '\n');
console.log('map.json:', map.concepts.length, 'concepts,', map.edges.length, 'edges');
