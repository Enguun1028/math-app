"""Copy the research fan-out data (research/fanout/*.json) into the app.
Run: python research/fanout/build-app-data.py   (after any fan-out file changes)

Writes:
  app/public/extras/<topic id>.json   practice questions, common mistakes, real-life uses, videos,
                                      interactives and ЭЕШ weight for one topic. Fetched when the topic
                                      opens, so the single-file build stays small.
  app/content/topic-content-extra.json  grade 1-4 basics and the 4 grade 12 elective topics
                                      (same shape as topic-content.json, used when that has no entry).
  app/content/search-aliases.json     extra search words per topic.
  app/content/videos.json             'topic:<id>' gets the first YouTube pick when the key is still empty.
The stories (stories.json) are left out on purpose: the owner will build HOT TOPICS by hand.
Everything copied here is DRAFT until the owner or a teacher checks it."""
import json, os, shutil

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))
app = os.path.join(root, 'app')


def load(name):
    return json.load(open(os.path.join(here, name), encoding='utf8'))


def lists(d):
    return {k: v for k, v in d.items() if isinstance(v, list) and not k.startswith('_')}


def dump(obj, *path, indent=None):
    with open(os.path.join(app, *path), 'w', encoding='utf8') as f:
        json.dump(obj, f, ensure_ascii=False, indent=indent)


ids = [c['id'] for c in json.load(open(os.path.join(app, 'content', 'map.json'), encoding='utf8'))['concepts']]
qs = {**lists(load('questions-num-alg.json')), **lists(load('questions-geo-stat-calc.json'))}
mis = {**lists(load('misconceptions-num-alg.json')), **lists(load('misconceptions-geo-stat-calc.json'))}
rw = lists(load('real-world.json'))
vid = lists(load('video-candidates.json'))
inter = lists(load('interactives.json'))
esh = load('esh-topic-weights.json')['weights']
aliases = lists(load('search-aliases.json'))
basics = {k: v for k, v in load('content-basics.json').items() if not k.startswith('_')}
gaps = {k: v for k, v in load('content-gaps.json').items() if not k.startswith('_')}

# One small file per topic.
out_dir = os.path.join(app, 'public', 'extras')
shutil.rmtree(out_dir, ignore_errors=True)
os.makedirs(out_dir)
videos_path = os.path.join(app, 'content', 'videos.json')
videos = json.load(open(videos_path, encoding='utf8'))
counts = dict(topics=0, q=0, mis=0, rw=0, v=0, it=0, first_video=0)
for i in ids:
    yt = [v for v in vid.get(i, []) if v.get('type') == 'youtube']
    key = 'topic:' + i
    if yt and key not in videos:
        videos[key] = {'type': 'youtube', 'src': yt[0]['id'], 'title': yt[0]['title'], 'draft': True}
        counts['first_video'] += 1
    shown = videos.get(key, {}).get('src')
    t = {
        'q': [{k: q[k] for k in ('level', 'q', 'choices', 'answer', 'why', 'traps') if k in q} for q in qs.get(i, [])],
        'mis': [{k: m.get(k) for k in ('wrong', 'example', 'why', 'fix', 'src')} for m in mis.get(i, [])],
        'rw': [{k: u.get(k) for k in ('title', 'text', 'mini', 'src')} for u in rw.get(i, [])],
        # Other videos: YouTube links and the ministry's lesson page (its MP4s have no reuse licence, so link out only).
        'v': [{'t': v['title'], 'ch': v.get('channel') if v['type'] == 'youtube' else 'БШУЯ теле хичээл', 'min': v.get('minutes'),
               'url': 'https://www.youtube.com/watch?v=' + v['id'] if v['type'] == 'youtube' else v.get('page') or v.get('url')}
              for v in vid.get(i, []) if v.get('id') != shown],
        'it': [{'n': x.get('name_mn') or x.get('name'), 'url': x['url'], 'k': x.get('kind'), 'mn': bool(x.get('mn'))}
               for x in inter.get(i, []) if isinstance(x, dict) and x.get('url')],
    }
    w = esh.get(i)
    if w and w.get('count'):
        t['esh'] = {'n': w['count'], 'pts': w.get('points')}
    t = {k: v for k, v in t.items() if v}
    if not t:
        continue
    dump(t, 'public', 'extras', i + '.json')
    counts['topics'] += 1
    for k in ('q', 'mis', 'rw', 'v', 'it'):
        counts[k] += len(t.get(k, []))
json.dump(videos, open(videos_path, 'w', encoding='utf8'), ensure_ascii=False, indent=1)

# Basics and elective topics: same shape as topic-content.json.
extra = {'_note': 'Generated by research/fanout/build-app-data.py from content-basics.json (2014 grade 1-4 textbooks) and content-gaps.json (grade 12 elective topics). Draft until the owner checks it.'}
for k, v in basics.items():
    extra[k] = {f: v[f] for f in ('def', 'src', 'formulas', 'rules', 'method', 'examples', 'visual') if v.get(f)}
for k, v in gaps.items():
    extra[k] = {**{f: v[f] for f in ('def', 'src', 'formulas', 'rules', 'method', 'examples') if v.get(f)}, 'elective': True}
dump(extra, 'content', 'topic-content-extra.json', indent=1)

dump({k: v for k, v in aliases.items() if k in ids}, 'content', 'search-aliases.json')
print(counts, '| basics', len(basics), '| elective', len(gaps), '| aliases', sum(len(v) for v in aliases.values()))
